#!/usr/bin/env node
// Regenerate src/lib/i18n-catalog.ts: every literal string passed to t("...")
// anywhere in src/. Run after adding UI copy: node scripts/gen-i18n-catalog.js
const { execSync } = require("child_process");
const fs = require("fs");
// A negative lookbehind excludes the `t` at the TAIL of an identifier
// (impor`t(`, .ge`t(`, `await impor`t(`...), which the old bare `t\(` regex
// wrongly captured - polluting the catalog with module paths, HTTP headers and
// query-param keys and wasting the daily translate budget translating them.
const out = execSync(
  `grep -rhoP '(?<![A-Za-z0-9_$])t\\("(?:[^"\\\\]|\\\\.)*"\\)' src --include='*.tsx' --include='*.ts'`,
  { encoding: "utf8" }
);
const strings = [...new Set(
  out.split("\n").filter(Boolean).map((l) => l.replace(/^t\("/, "").replace(/"\)$/, ""))
)].sort();
const body =
  "// AUTO-GENERATED by scripts/gen-i18n-catalog.js - do not edit by hand.\n" +
  "// Every literal t(\"...\") string in the app, so a language switch can\n" +
  "// translate ALL pages up front (not just the ones already mounted).\n" +
  "export const I18N_CATALOG: string[] = [\n" +
  strings.map((s) => `  ${JSON.stringify(s)},`).join("\n") +
  "\n];\n";
fs.writeFileSync("src/lib/i18n-catalog.ts", body);
console.log(`i18n catalogue: ${strings.length} strings`);
